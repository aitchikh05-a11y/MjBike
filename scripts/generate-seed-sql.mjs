/**
 * Generates `supabase/seed.sql` from `src/data/seed.ts` so the demo backend and the
 * real database always start from identical content.
 *
 *   node scripts/generate-seed-sql.mjs
 *
 * Seed identifiers are not UUIDs (they are readable for the demo), so we derive a
 * stable UUID v5-style identifier from each string. Relations stay consistent because
 * every reference goes through the same function.
 */
import { createHash } from 'node:crypto';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const outfile = path.join(mkdtempSync(path.join(tmpdir(), 'mjb-seed-')), 'seed.mjs');

await build({
  entryPoints: [path.join(root, 'src/data/seed.ts')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'node',
  logLevel: 'error',
  alias: {
    '@shared': path.join(root, 'shared'),
    '@': path.join(root, 'src'),
  },
});

const seed = await import(pathToFileURL(outfile).href);

const uuidFor = (value) => {
  if (!value) return null;
  const hex = createHash('sha1').update(String(value)).digest('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
};

const quote = (value) => {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  return `'${String(value).replace(/'/g, "''")}'`;
};

const json = (value) => `${quote(JSON.stringify(value ?? null))}::jsonb`;

const lines = [];
const push = (...parts) => lines.push(...parts);

push(
  '-- =====================================================================',
  '-- MJ Bike Tangier — seed data',
  '--',
  '-- Generated by `node scripts/generate-seed-sql.mjs` from src/data/seed.ts.',
  '-- Do not edit by hand: change src/data/seed.ts and regenerate so the demo',
  '-- backend and the database stay identical.',
  '--',
  '-- Run with: supabase db reset (local) or psql -f supabase/seed.sql (hosted).',
  '-- Testimonials are intentionally empty: no invented reviews.',
  '-- =====================================================================',
  '',
  'begin;',
  '',
  '-- Wipe catalogue content (reservations are left alone; use `supabase db reset`).',
  "delete from public.offer_translations;",
  "delete from public.service_translations;",
  "delete from public.offers;",
  "delete from public.gallery_items;",
  "delete from public.testimonials;",
  "delete from public.bicycles;",
  "delete from public.availability_blocks;",
  "delete from public.availability_rules;",
  "delete from public.services;",
  "delete from public.site_settings;",
  '',
  '-- ---------------------------------------------------------------------',
  '-- Site settings',
  '-- ---------------------------------------------------------------------',
);

const settings = seed.SEED_SETTINGS;
push(
  `insert into public.site_settings (id, business_name, tagline, phone, whatsapp, email, address, maps_url, instagram_url, facebook_url, tiktok_url, youtube_url, opening_hours, about_claims, faq, currency, timezone) values (
  ${quote(uuidFor(settings.id))}, ${quote(settings.business_name)}, ${json(settings.tagline)}, ${quote(settings.phone)}, ${quote(settings.whatsapp)},
  ${quote(settings.email)}, ${json(settings.address)}, ${quote(settings.maps_url)}, ${quote(settings.instagram_url)},
  ${quote(settings.facebook_url)}, ${quote(settings.tiktok_url)}, ${quote(settings.youtube_url)},
  ${json(settings.opening_hours)}, ${json(settings.about_claims)}, ${json(settings.faq)},
  ${quote(settings.currency)}, ${quote(settings.timezone)}
);`,
  '',
  '-- ---------------------------------------------------------------------',
  '-- Services + translations',
  '-- ---------------------------------------------------------------------',
);

const serviceUuid = new Map();
for (const service of seed.SEED_SERVICES) {
  const id = uuidFor(service.id);
  serviceUuid.set(service.id, id);
  push(
    `insert into public.services (id, slug, kind, image_url, gallery, price_unit, base_price, duration_options, default_duration_hours, capacity, min_units, max_units, addons, is_active, is_featured, sort_order) values (
  ${quote(id)}, ${quote(service.slug)}, ${quote(service.kind)}, ${quote(service.image_url)}, ${json(service.gallery)},
  ${quote(service.price_unit)}, ${service.base_price}, ${json(service.duration_options)}, ${service.default_duration_hours},
  ${service.capacity}, ${service.min_units}, ${service.max_units}, ${json(service.addons)},
  ${quote(service.is_active)}, ${quote(service.is_featured)}, ${service.sort_order}
);`,
  );
  for (const translation of service.translations) {
    push(
      `insert into public.service_translations (service_id, locale, name, short_description, description, highlights, meta_title, meta_description) values (
  ${quote(id)}, ${quote(translation.locale)}, ${quote(translation.name)}, ${quote(translation.short_description)},
  ${quote(translation.description)}, ${json(translation.highlights)}, ${quote(translation.meta_title)}, ${quote(translation.meta_description)}
);`,
    );
  }
}

push('', '-- ---------------------------------------------------------------------', '-- Offers + translations', '-- ---------------------------------------------------------------------');
for (const offer of seed.SEED_OFFERS) {
  const id = uuidFor(offer.id);
  push(
    `insert into public.offers (id, slug, service_id, image_url, price, compare_at_price, duration_hours, validity_start, validity_end, capacity, status, is_featured, sort_order) values (
  ${quote(id)}, ${quote(offer.slug)}, ${quote(serviceUuid.get(offer.service_id))}, ${quote(offer.image_url)},
  ${offer.price}, ${quote(offer.compare_at_price)}, ${offer.duration_hours}, ${quote(offer.validity_start)}, ${quote(offer.validity_end)},
  ${quote(offer.capacity)}, ${quote(offer.status)}, ${quote(offer.is_featured)}, ${offer.sort_order}
);`,
  );
  for (const translation of offer.translations) {
    push(
      `insert into public.offer_translations (offer_id, locale, title, short_description, description, included) values (
  ${quote(id)}, ${quote(translation.locale)}, ${quote(translation.title)}, ${quote(translation.short_description)},
  ${quote(translation.description)}, ${json(translation.included)}
);`,
    );
  }
}

push('', '-- ---------------------------------------------------------------------', '-- Gallery', '-- ---------------------------------------------------------------------');
for (const item of seed.SEED_GALLERY) {
  push(
    `insert into public.gallery_items (id, kind, media_url, thumbnail_url, title, caption, category, is_published, is_featured, sort_order) values (
  ${quote(uuidFor(item.id))}, ${quote(item.kind)}, ${quote(item.media_url)}, ${quote(item.thumbnail_url)},
  ${json(item.title)}, ${json(item.caption)}, ${quote(item.category)}, ${quote(item.is_published)}, ${quote(item.is_featured)}, ${item.sort_order}
);`,
  );
}

push('', '-- ---------------------------------------------------------------------', '-- Opening hours (every day 09:00–21:00, hourly slots)', '-- ---------------------------------------------------------------------');
for (const rule of seed.SEED_AVAILABILITY_RULES) {
  push(
    `insert into public.availability_rules (day_of_week, open_time, close_time, slot_interval_minutes, capacity, is_active) values (
  ${rule.day_of_week}, ${quote(rule.open_time)}, ${quote(rule.close_time)}, ${rule.slot_interval_minutes}, ${quote(rule.capacity)}, ${quote(rule.is_active)}
);`,
  );
}

push('', '-- ---------------------------------------------------------------------', '-- Fleet', '-- ---------------------------------------------------------------------');
for (const bike of seed.SEED_BICYCLES) {
  push(
    `insert into public.bicycles (id, internal_code, name, category, size, service_id, quantity, status, purchase_date, last_service_at, maintenance_notes) values (
  ${quote(uuidFor(bike.id))}, ${quote(bike.internal_code)}, ${quote(bike.name)}, ${quote(bike.category)}, ${quote(bike.size)},
  ${quote(serviceUuid.get(bike.service_id))}, ${bike.quantity}, ${quote(bike.status)}, ${quote(bike.purchase_date)},
  ${quote(bike.last_service_at)}, ${quote(bike.maintenance_notes)}
);`,
  );
}

push(
  '',
  '-- ---------------------------------------------------------------------',
  '-- Demo testimonies: none. Add real, consented customer quotes in the admin.',
  '-- ---------------------------------------------------------------------',
  '',
  'commit;',
  '',
  '-- =====================================================================',
  '-- Administrator accounts',
  '--',
  '-- Supabase Auth users cannot be seeded safely from plain SQL on a hosted',
  '-- project. Create the first super admin in the dashboard (Authentication →',
  '-- Users → Add user), then promote that user with:',
  '--',
  '--   update public.profiles set role = \'super_admin\' where email = \'you@example.com\';',
  '--',
  '-- New team members are invited from /admin/settings by a super admin, which',
  '-- creates the auth user and its profile row through the Pages Function.',
  '-- =====================================================================',
  '',
);

writeFileSync(path.join(root, 'supabase/seed.sql'), `${lines.join('\n')}\n`, 'utf8');
console.log(`supabase/seed.sql written (${lines.length} lines)`);
